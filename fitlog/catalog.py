CUSTOM_GROUP = "Мои"

_INDEX = {normalize_exercise(name): (name, group)
          for group, names in CATALOG.items() for name in names}


def display_name(exercise: str) -> str:
    """Красивое название для упражнения из базы (там хранится в нижнем регистре)."""
    if exercise in _INDEX:
        return _INDEX[exercise][0]
    return exercise[:1].upper() + exercise[1:]


def group_of(exercise: str) -> str:
    return _INDEX[exercise][1] if exercise in _INDEX else CUSTOM_GROUP


def is_custom(exercise: str) -> bool:
    return exercise not in _INDEX
